func TestCLIReadsGnuPGKeys(t *testing.T) {
	gpg, env := gpgEnv(t)
	const passphrase = "correct horse battery staple"
	runGPG(t, gpg, env, nil,
		"--batch", "--pinentry-mode", "loopback", "--passphrase", passphrase,
		"--quick-generate-key", "Bob <bob@example.invalid>", "future-default", "default", "never",
	)
	publicArmor := runGPG(t, gpg, env, nil, "--armor", "--export", "bob@example.invalid")
	privateArmor := runGPG(t, gpg, env, nil,
		"--batch", "--yes", "--pinentry-mode", "loopback", "--passphrase", passphrase,
		"--armor", "--export-secret-keys", "bob@example.invalid",
	)

	plaintext := []byte("generated by gpg\n")
	ciphertext, _, _, err := encryptF2F([]string{string(publicArmor)}, "", nil, plaintext, true)
	if err != nil {
		t.Fatalf("encrypt to gpg key: %v", err)
	}
	decrypted, _, err := decryptF2F(string(privateArmor), []byte(passphrase), ciphertext, "", 1<<20)
	if err != nil {
		t.Fatalf("decrypt gpg key: %v", err)
	}
	if !bytes.Equal(decrypted, plaintext) {
		t.Fatalf("plaintext = %q", decrypted)
	}
}
