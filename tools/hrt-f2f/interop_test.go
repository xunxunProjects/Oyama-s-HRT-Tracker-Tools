package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

func gpgEnv(t *testing.T) (string, []string) {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("GnuPG interoperability is exercised on Unix")
	}
	gpg, err := exec.LookPath("gpg")
	if err != nil {
		t.Skip("gpg is not installed")
	}
	home := filepath.Join(t.TempDir(), "gnupg")
	if err := os.Mkdir(home, 0o700); err != nil {
		t.Fatal(err)
	}
	return gpg, append(os.Environ(), "GNUPGHOME="+home)
}

func runGPG(t *testing.T, gpg string, env []string, stdin []byte, args ...string) []byte {
	t.Helper()
	command := exec.Command(gpg, args...)
	command.Env = env
	if stdin != nil {
		command.Stdin = bytes.NewReader(stdin)
	}
	var stderr bytes.Buffer
	command.Stderr = &stderr
	output, err := command.Output()
	if err != nil {
		t.Fatalf("gpg %s: %v\n%s", strings.Join(args, " "), err, stderr.String())
	}
	return output
}

